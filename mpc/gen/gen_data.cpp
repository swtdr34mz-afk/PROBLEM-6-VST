/* The MPC build's tables, made from the firmware's own C (dsp/params.c, dsp/presets.c) at build time: the MPC SDK
 * compiles C++ only, and those files use C's designated initialisers. Built natively (the C files as C) and run by
 * mpc/build.py, it writes p67_data.cpp: the parameters, the factory programs, the sync tables, and every
 * parameter's every value as the firmware shows it (so the MPC's screen reads as the FM-1's and the VST's).
 *
 *   gen_data <out.cpp> */
extern "C" {
#include "engine.h"
}
#include <cstdio>
#include <string>

#define P67_TEXT_LEN 10                  /* (as mpc/plugin/src/p67_data.h) */

static std::string esc(const char *s)
{
    std::string o = "\"";
    for (; *s; s++) {
        if (*s == '"' || *s == '\\')
            o += '\\';
        o += *s;
    }
    return o + "\"";
}

int main(int argc, char **argv)
{
    if (argc < 2)
        return 2;
    FILE *f = std::fopen(argv[1], "w");
    if (!f)
        return 1;
    std::fprintf(f, "/* generated by mpc/gen/gen_data.cpp from dsp/params.c and dsp/presets.c: do not edit */\n");
    std::fprintf(f, "extern \"C\" {\n#include \"engine.h\"\n}\n#include \"p67_data.h\"\n\n");
    std::fprintf(f, "extern \"C\" const uint16_t LSY_TICKS[NLSY] = {");
    for (int i = 0; i < NLSY; i++)
        std::fprintf(f, "%s%u", i ? ", " : "", (unsigned)LSY_TICKS[i]);
    std::fprintf(f, "};\nextern \"C\" const uint8_t DL_SYNC_TICKS[NDLS] = {");
    for (int i = 0; i < NDLS; i++)
        std::fprintf(f, "%s%u", i ? ", " : "", (unsigned)DL_SYNC_TICKS[i]);
    std::fprintf(f, "};\nextern \"C\" const char *const DL_SYNC_NAME[NDLS] = {");
    for (int i = 0; i < NDLS; i++)
        std::fprintf(f, "%s%s", i ? ", " : "", esc(DL_SYNC_NAME[i]).c_str());
    std::fprintf(f, "};\n\n");
    for (int i = 0; i < NPARAM; i++)
        if (PARAMS[i].kind == PK_CHOICE) {
            std::fprintf(f, "static const char *const CH_%d[] = {", i);
            for (int k = 0; k <= PARAMS[i].max; k++)
                std::fprintf(f, "%s%s", k ? ", " : "", esc(PARAMS[i].choice[k]).c_str());
            std::fprintf(f, "};\n");
        }
    std::fprintf(f, "extern \"C\" const param_t PARAMS[NPARAM] = {\n");
    for (int i = 0; i < NPARAM; i++) {
        char ch[16] = "nullptr";
        if (PARAMS[i].kind == PK_CHOICE)
            std::snprintf(ch, sizeof ch, "CH_%d", i);
        std::fprintf(f, "    {%s, %u, %u, %s},\n", esc(PARAMS[i].name).c_str(), (unsigned)PARAMS[i].kind,
                     (unsigned)PARAMS[i].max, ch);
    }
    std::fprintf(f, "};\n\nextern \"C\" const patch_t FACTORY[NPRESETS] = {\n");
    for (int i = 0; i < NPRESETS; i++) {
        std::fprintf(f, "    {{");        /* (a name of NAME_LEN characters has no nought: as characters) */
        for (int k = 0; k < NAME_LEN && FACTORY[i].name[k]; k++)
            std::fprintf(f, "%s'%c'", k ? ", " : "", FACTORY[i].name[k]);
        std::fprintf(f, "}, {");
        for (int k = 0; k < NPARAM; k++)
            std::fprintf(f, "%s%u", k ? ", " : "", (unsigned)FACTORY[i].p[k]);
        std::fprintf(f, "}},\n");
    }
    std::fprintf(f, "};\n\n/* every value's text (P67_TEXT_LEN with its nought) */\nconst char P67_TEXT[NPARAM][128][P67_TEXT_LEN] = {\n");
    for (int i = 0; i < NPARAM; i++) {
        std::fprintf(f, "    {");
        for (int v = 0; v < 128; v++) {
            char t[64] = "";
            if (v <= PARAMS[i].max)
                param_text(i, v, t);
            t[P67_TEXT_LEN - 1] = 0;
            std::fprintf(f, "%s%s", v ? ", " : "", esc(t).c_str());
        }
        std::fprintf(f, "},\n");
    }
    std::fprintf(f, "};\n");
    std::fclose(f);
    return 0;
}
