"""PROBLEM 6 for the MPC (formerly PROPHETIC 6): builds the plugin folder with Akai's MPC Plugin SDK.

The MPC SDK builds a project of C++ files in one src/ folder. This script makes that project from this repository,
so the MPC plugin always has the same engine as the VST3 (nothing copied by hand, nothing in two places):

  1. mpc/build/PROBLEM 6/      the SDK project: plugin.json, README.md and skins/ (the VST3's panel as the MPC's
                                 screen: mpc/skin/) from mpc/plugin/, and in src/
                                 mpc/plugin/src/*, the engine (src/P67Engine.*, dsp/engine.c, fx.c, clock.c and their
                                 headers, shim/plat.h) and p67_data.cpp
  2. p67_data.cpp                generated by mpc/gen/gen_data.cpp from dsp/params.c and dsp/presets.c (C, built here
                                 as C with the computer's own compiler): the parameters, the factory programs, every
                                 value's text
  3. the SDK's tools/build.py    native build + host simulator, arm32 and arm64, the skins, version.xml, validation

    python3 mpc/build.py --sdk /path/to/mpc-plugin-builder-sdk [--target native|arm32|arm64|all] [--toolchain zig|gcc]

The SDK: https://github.com/inmusic-software/mpc-plugin-builder-sdk (or MPC_SDK=/path). The result:
mpc/build/PROBLEM 6/build/swtdr34mz - VST - PROBLEM 6/ (copy it into "VST2 Plugins" on a drive of the MPC).
"""
import argparse
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
NAME = "PROBLEM 6"
ENGINE = [  # (from the repository, into the project's src/)
    "src/P67Engine.cpp", "src/P67Engine.h", "src/KeySplit.h",
    "dsp/engine.c", "dsp/fx.c", "dsp/clock.c", "dsp/engine.h", "dsp/core.h", "dsp/fastmath.h",
    "shim/plat.h",
]
DEFINES = ["P67_PLUGIN=1", "PLAT_HOST=1", "P67_MPC=1"]


def run(argv, **kw):
    print("+ " + " ".join('"%s"' % a if " " in a else a for a in argv), flush=True)
    subprocess.check_call(argv, **kw)


def find_tool(env, names):
    if os.environ.get(env):
        return os.environ[env]
    for n in names:
        p = shutil.which(n)
        if p:
            return p
    sys.exit("no %s found (set %s)" % ("/".join(names), env))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--sdk", default=os.environ.get("MPC_SDK", os.path.join(ROOT, "..", "mpc-plugin-builder-sdk")),
                    help="the MPC Plugin SDK's folder (default: $MPC_SDK, or beside this repository)")
    ap.add_argument("--target", default="all", help="native, arm32, arm64 or all (the SDK's build.py)")
    ap.add_argument("--toolchain", default=None, help="zig (the SDK's default), gcc or docker")
    ap.add_argument("--no-validate", action="store_true")
    a = ap.parse_args()

    sdk = os.path.abspath(a.sdk)
    sdk_build = os.path.join(sdk, "tools", "build.py")
    if not os.path.isfile(sdk_build):
        sys.exit("the MPC Plugin SDK is not at %s (--sdk or MPC_SDK; git clone "
                 "https://github.com/inmusic-software/mpc-plugin-builder-sdk)" % sdk)

    # 1. the project
    proj = os.path.join(HERE, "build", NAME)
    src = os.path.join(proj, "src")
    if os.path.isdir(src):
        shutil.rmtree(src)
    os.makedirs(src)
    for f in ("plugin.json", "README.md"):
        shutil.copy2(os.path.join(HERE, "plugin", f), os.path.join(proj, f))
    skins = os.path.join(proj, "skins")  # (the SDK copies a project's skins/ as they are, as "Plugin Skins")
    if os.path.isdir(skins):
        shutil.rmtree(skins)
    shutil.copytree(os.path.join(HERE, "plugin", "skins"), skins)
    stale = os.path.join(proj, "ui.json")
    if os.path.isfile(stale):
        os.remove(stale)
    for f in os.listdir(os.path.join(HERE, "plugin", "src")):
        shutil.copy2(os.path.join(HERE, "plugin", "src", f), os.path.join(src, f))
    for f in ENGINE:
        shutil.copy2(os.path.join(ROOT, f), os.path.join(src, os.path.basename(f)))

    # 2. the tables, from the firmware's C
    gen = os.path.join(HERE, "build", "gen")
    os.makedirs(gen, exist_ok=True)
    cc = find_tool("CC", ["cc", "gcc", "clang"])
    cxx = find_tool("CXX", ["c++", "g++", "clang++"])
    inc = ["-I" + os.path.join(ROOT, "dsp"), "-I" + os.path.join(ROOT, "shim")] + ["-D" + d for d in DEFINES]
    objs = []
    for c in ("params.c", "presets.c"):
        o = os.path.join(gen, c + ".o")
        run([cc, "-std=c11", "-O1", "-c"] + inc + [os.path.join(ROOT, "dsp", c), "-o", o])
        objs.append(o)
    exe = os.path.join(gen, "gen_data" + (".exe" if os.name == "nt" else ""))
    run([cxx, "-std=c++17", "-O1"] + inc + [os.path.join(HERE, "gen", "gen_data.cpp")] + objs + ["-o", exe])
    run([exe, os.path.join(src, "p67_data.cpp")])

    # 3. the SDK's build
    argv = [sys.executable, sdk_build, proj, "--target", a.target]
    for d in DEFINES:
        argv += ["--define", d]
    if a.toolchain:
        argv += ["--toolchain", a.toolchain]
    if a.no_validate:
        argv.append("--no-validate")
    run(argv)
    out = os.path.join(proj, "build", "swtdr34mz - VST - " + NAME)
    if os.path.isdir(out):
        print("\nthe plugin folder: %s" % out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
